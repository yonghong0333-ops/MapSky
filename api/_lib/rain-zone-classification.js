function normalizeCounty(name) {
  // 政府圖資(taiwan-atlas 等) 常用「台」，CWA CAP 特報用「臺」，統一轉成「臺」方便比對
  return String(name || "").replace(/^台/, "臺");
}

function normalizeAreaDesc(areaDesc) {
  return normalizeCounty(String(areaDesc || "").trim());
}

// 分區的顯示順序，跟中央氣象署網頁彈出視窗的順序一致
const ZONE_ORDER = ["平地", "恆春半島", "山區", "綠島", "蘭嶼"];

/**
 * @param {string} areaDesc 例如 "臺東縣達仁鄉"（縣市＋鄉鎮市區，中間不留空格）
 * @returns {"平地"|"恆春半島"|"山區"|"綠島"|"蘭嶼"}
 */
function classifyZone(areaDesc) {
  const key = normalizeAreaDesc(areaDesc);
  if (key === GREEN_ISLAND) return "綠島";
  if (key === ORCHID_ISLAND) return "蘭嶼";
  if (HENGCHUN_TOWNSHIPS.has(key)) return "恆春半島";
  if (MOUNTAIN_TOWNSHIPS.has(key)) return "山區";
  return "平地";
}

