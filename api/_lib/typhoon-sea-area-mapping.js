// 把 CAP <areaDesc> 的海域名稱轉成鄰近沿海縣市清單，查不到就回傳空陣列
function seaAreaToCounties(areaName) {
  const key = String(areaName || "").trim();
  return SEA_AREA_TO_COASTAL_COUNTIES[key] || [];
}

// 把 CAP <areaDesc>（陸上颱風警報，通常直接是縣市，偶爾帶「全部」等字樣）
// 轉成縣市名稱；比對不到已知縣市清單就回傳 null
function landAreaToCounty(areaName) {
  const key = normalizeCounty(String(areaName || "").trim());
  let best = null;
  for (const county of COUNTY_LIST) {
    if (key.startsWith(county) && (!best || county.length > best.length)) best = county;
  }
  return best;
}

